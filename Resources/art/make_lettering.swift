// Turns the banner's lettering into SVG path data, so Inkscape (which can't be relied on
// to pick SF Pro Rounded at the right weight) draws it the same everywhere. Run it only
// when the words change:
//
//     swift Resources/art/make_lettering.swift > Resources/art/lettering.py
//
// Each entry is (advance width, path data), drawn from a baseline origin at (0, 0) with
// y pointing down, at the size given below.
import AppKit
import CoreText

func rounded(_ size: CGFloat, _ weight: NSFont.Weight) -> CTFont {
    let base = NSFont.systemFont(ofSize: size, weight: weight)
    let descriptor = base.fontDescriptor.withDesign(.rounded) ?? base.fontDescriptor
    return NSFont(descriptor: descriptor, size: size) ?? base
}

func outline(_ text: String, size: CGFloat, weight: NSFont.Weight, tracking: CGFloat) -> (CGFloat, String) {
    let attributed = NSAttributedString(string: text, attributes: [
        .font: rounded(size, weight), .kern: size * tracking,
    ])
    let line = CTLineCreateWithAttributedString(attributed)
    var d = ""
    func f(_ v: CGFloat) -> String {
        let s = String(format: "%.1f", v)
        return s.hasSuffix(".0") ? String(s.dropLast(2)) : s
    }
    for run in CTLineGetGlyphRuns(line) as! [CTRun] {
        let count = CTRunGetGlyphCount(run)
        var glyphs = [CGGlyph](repeating: 0, count: count)
        var positions = [CGPoint](repeating: .zero, count: count)
        CTRunGetGlyphs(run, CFRange(location: 0, length: 0), &glyphs)
        CTRunGetPositions(run, CFRange(location: 0, length: 0), &positions)
        let attributes = CTRunGetAttributes(run) as NSDictionary
        let font = attributes[kCTFontAttributeName as String] as! CTFont
        for i in 0..<count {
            guard let path = CTFontCreatePathForGlyph(font, glyphs[i], nil) else { continue }
            let o = positions[i]
            path.applyWithBlock { element in
                let p = element.pointee.points
                func pt(_ n: Int) -> String { "\(f(o.x + p[n].x)),\(f(-(o.y + p[n].y)))" }
                switch element.pointee.type {
                case .moveToPoint: d += "M\(pt(0))"
                case .addLineToPoint: d += "L\(pt(0))"
                case .addQuadCurveToPoint: d += "Q\(pt(0)) \(pt(1))"
                case .addCurveToPoint: d += "C\(pt(0)) \(pt(1)) \(pt(2))"
                case .closeSubpath: d += "Z"
                @unknown default: break
                }
            }
        }
    }
    return (CGFloat(CTLineGetTypographicBounds(line, nil, nil, nil)), d)
}

let lettering: [(String, String, CGFloat, NSFont.Weight, CGFloat)] = [
    ("WORDMARK", "Slimreel", 160, .black, -0.01),
    ("TAGLINE", "Find and shrink your biggest videos.", 34, .heavy, 0),
    ("FOOTER", "Everything stays on your Mac. Free & open source.", 26, .bold, 0),
]
print("# Generated by make_lettering.swift from SF Pro Rounded. Don't edit by hand.")
for (name, text, size, weight, tracking) in lettering {
    let (width, d) = outline(text, size: size, weight: weight, tracking: tracking)
    print("\(name) = (\(String(format: "%.1f", width)), \"\(d)\")  # \"\(text)\", \(Int(size)) px")
}
